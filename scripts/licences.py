#!/usr/bin/env python3
"""Writes docs/licences.md: every crate the OfficeCraft app is built from, its version and licence,
plus the bundled assets the four Craft repos credit in their ATTRIBUTION files (Phase 8.4).

Fails (exit 1) on any crate whose licence isn't on the allowlist, so a copyleft or unknown
licence can't slip into a release unnoticed.

    python3 scripts/licences.py [--check]    # --check: verify only, don't write the file
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Licences a closed or open app may ship under without passing its own source on.
ALLOWED = {
    "MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib",
    "Unicode-3.0", "Unicode-DFS-2016", "BSL-1.0", "CC0-1.0", "0BSD", "Unlicense", "OFL-1.1", "MPL-2.0",
    "CDLA-Permissive-2.0", "bzip2-1.0.6", "NCSA",
}
# MPL-2.0 is file-level copyleft: fine to ship, but changes to MPL files must be shared. Listed
# separately in the report.
WEAK_COPYLEFT = {"MPL-2.0"}


def allowed(expr):
    """An SPDX expression: OR needs one allowed side, AND needs all."""
    if not expr:
        return False
    expr = expr.replace("/", " OR ").strip()
    if expr.startswith("(") and expr.endswith(")"):
        expr = expr[1:-1]
    for alt in re.split(r"\s+OR\s+", expr):
        parts = [p.strip(" ()") for p in re.split(r"\s+AND\s+", alt)]
        if all(p in ALLOWED for p in parts):
            return True
    return False


def main():
    check_only = "--check" in sys.argv
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--offline", "--manifest-path", os.path.join(ROOT, "Cargo.toml")],
        cwd=ROOT, stderr=subprocess.DEVNULL))
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    # The app and what it needs to build and run (not dev- or build-only tools of other crates).
    start = next(p["id"] for p in meta["packages"] if p["name"] == "officecraft" and p.get("source") is None)
    seen, todo = set(), [start]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            kinds = {k.get("kind") for k in d.get("dep_kinds", [])}
            if kinds - {"dev"}:
                todo.append(d["pkg"])
    rows, bad, weak = [], [], []
    for i in seen:
        p = pkgs[i]
        lic = p.get("license") or ("(see " + os.path.basename(p["license_file"]) + ")" if p.get("license_file") else "")
        src = p.get("source") or "path"
        origin = "crates.io" if src.startswith("registry") else ("git" if src.startswith("git") else "this workspace / vendored Craft repo")
        rows.append((p["name"], p["version"], lic, origin))
        if p["name"].startswith("officecraft"):
            continue
        if not allowed(p.get("license") or ""):
            bad.append((p["name"], p["version"], lic or "none given"))
        elif any(w in (p.get("license") or "") for w in WEAK_COPYLEFT) and not allowed((p.get("license") or "").replace("MPL-2.0", "X")):
            weak.append((p["name"], p["version"], lic))
    rows.sort()
    counts = {}
    for _, _, lic, _ in rows:
        counts[lic] = counts.get(lic, 0) + 1

    out = ["# Licences", "",
           "Generated by `python3 scripts/licences.py` from `cargo metadata`; don't edit by hand.", "",
           f"OfficeCraft (MIT OR Apache-2.0) is built from **{len(rows)} crates**. The build fails on any licence "
           "outside the allowlist in `scripts/licences.py`.", ""]
    if weak:
        out += ["## File-level copyleft (MPL-2.0)", "",
                "These may ship in OfficeCraft. Changes made to their own files must be published under the MPL.", ""]
        out += [f"- {n} {v} ({l})" for n, v, l in sorted(weak)] + [""]
    out += ["## Bundled assets", "",
            "Fonts, icons and data the four Craft repos bundle, as each credits them:", ""]
    for repo in ["wordcraft", "gridcraft", "deckcraft", "pdfcraft", "craft-fonts", "craft-libs"]:
        d = os.path.join(ROOT, "vendor", repo)
        files = [f for f in sorted(os.listdir(d)) if f.upper().startswith(("ATTRIBUTION", "NOTICE", "LICENSES.TOML"))] if os.path.isdir(d) else []
        if files:
            out.append(f"- **{repo}**: " + ", ".join(f"`vendor/{repo}/{f}`" for f in files))
    out += ["", "## Licences in use", "", "| Licence | Crates |", "|---|---|"]
    out += [f"| {l or '(none given)'} | {n} |" for l, n in sorted(counts.items(), key=lambda x: -x[1])]
    out += ["", "## Every crate", "", "| Crate | Version | Licence | From |", "|---|---|---|---|"]
    out += [f"| {n} | {v} | {l} | {o} |" for n, v, l, o in rows]
    text = "\n".join(out) + "\n"

    if bad:
        print("Licences outside the allowlist:")
        for n, v, l in sorted(bad):
            print(f"  {n} {v}: {l}")
    if not check_only:
        with open(os.path.join(ROOT, "docs", "licences.md"), "w") as f:
            f.write(text)
    print(f"{len(rows)} crates; {len(bad)} outside the allowlist; {len(weak)} MPL-2.0")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
